// SelectionInput is the browser's raw description of an md selection.
//
// Key contract: the frontend does **not** compute source-file offsets
// itself. It only reports the start/end offsets of the "nearest block
// carrying data-sourcepos", the selected rendered text, and the rendered
// text immediately surrounding it within that block; the Go side then
// quote-matches within that block's source (exact match first, falling back
// to bitap fuzzy matching) to compute the final Anchor. When matching fails,
// it falls back to anchoring the whole block and sets Anchor.Approx=true.
type SelectionInput struct {
	BlockStart int    `json:"block_start"` // the start of data-sourcepos
	BlockEnd   int    `json:"block_end"`   // the end of data-sourcepos
	Exact      string `json:"exact"`       // the selected rendered text (may differ from source due to stripped md markup)
	Before     string `json:"before"`      // up to 64 characters of rendered text before the selection, within the same block
	After      string `json:"after"`       // up to 64 characters of rendered text after the selection, within the same block
}

// ElementInput is the raw description of an html artifact element anchor.
type ElementInput struct {
	AID   string `json:"aid"`             // the target element's data-aid
	Quote string `json:"quote,omitempty"` // optional selected text within the element, for refinement
}

// EventRequest is the request body for POST /api/docs/{id}/events.
// Type determines which fields are required; see blueprint.md's "HTTP API
// contract" section.
type EventRequest struct {
	Type      string          `json:"type"`                // create|reply|edit|addressed|resolve|reopen
	Thread    string          `json:"thread,omitempty"`    // required for everything except create
	Target    string          `json:"target,omitempty"`    // required for edit: a thread id or reply id
	Body      string          `json:"body,omitempty"`      // required for create/reply/edit
	Author    string          `json:"author,omitempty"`    // filled in by the server's identity rules when omitted
	Commit    string          `json:"commit,omitempty"`    // optional for addressed
	Note      string          `json:"note,omitempty"`      // optional for addressed/reopen
	Selection *SelectionInput `json:"selection,omitempty"` // required for create on an md document
	Element   *ElementInput   `json:"element,omitempty"`   // required for create on an html document
}

// EventResponse is the response body for POST /api/docs/{id}/events.
type EventResponse struct {
	OK      string `json:"ok"`               // always "ok"
	Thread  string `json:"thread"`           // the affected thread id (the newly assigned id for create)
	EventID string `json:"event_id"`         // the event id
	Status  string `json:"status,omitempty"` // the thread's new status after folding
}

