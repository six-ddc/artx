// NewDocResponse is the output of `artx new --json`, and also the response
// body for POST /api/docs.
type NewDocResponse struct {
	ID   string `json:"id"`
	Path string `json:"path"`
	URL  string `json:"url"`
	Slug string `json:"slug"`
	Type string `json:"type"`
}

// NewDocRequest is the request body for POST /api/docs.
type NewDocRequest struct {
	Slug  string `json:"slug"`
	Type  string `json:"type"`
	Title string `json:"title,omitempty"`
}

// HealthResponse is the response body for GET /api/health. The CLI uses it
// to confirm that the serve instance it detected belongs to the same vault.
type HealthResponse struct {
	OK      string `json:"ok"`      // always "ok"
	Version string `json:"version"` // art's version
	Vault   string `json:"vault"`   // vault name
	Root    string `json:"root"`    // absolute vault path
	Watch   bool   `json:"watch"`   // whether the watcher is enabled
}

// CompactRequest is the request body for POST /api/compact; an empty Doc
// means all documents.
type CompactRequest struct {
	Doc   string `json:"doc,omitempty"`
	Force bool   `json:"force,omitempty"` // ignore the threshold and compact regardless
}

// CompactStat is the compaction result for a single document.
type CompactStat struct {
	Doc             string `json:"doc"`
	EventsBefore    int    `json:"events_before"`
	EventsAfter     int    `json:"events_after"`
	ThreadsArchived int    `json:"threads_archived"`
	BytesBefore     int64  `json:"bytes_before"`
	BytesAfter      int64  `json:"bytes_after"`
	Skipped         bool   `json:"skipped,omitempty"` // below threshold and not forced
}

// CompactResponse is the output of both POST /api/compact and
// `artx compact --json`.
type CompactResponse struct {
	Stats  []CompactStat `json:"stats"`
	Commit string        `json:"commit,omitempty"` // sha of the git commit compaction produced
}

// ErrorResponse is the uniform response body for all 4xx/5xx responses.
type ErrorResponse struct {
	Error   string `json:"error"`   // machine-readable error code, see blueprint.md
	Message string `json:"message"` // human-readable explanation
	Detail  string `json:"detail,omitempty"`
}

// Standard error codes. See blueprint.md for the HTTP status / CLI exit code mapping.
const (
	ErrNotFound     = "not_found"    // 404 / exit 2
	ErrBadRequest   = "bad_request"  // 400 / exit 1
	ErrUnauthorized = "unauthorized" // 401 / exit 1
	ErrForbidden    = "forbidden"    // 403 / exit 1
	ErrConflict     = "conflict"     // 409 / exit 1
	ErrInternal     = "internal"     // 500 / exit 1
)

// ---------------------------------------------------------------------------
// SSE
// ---------------------------------------------------------------------------

// SSE event names. The data payload is always the JSON of the corresponding
// struct below.
const (
	SSEComments = "comments" // a document's comments changed
	SSEDoc      = "doc"      // a document's content changed (including remap / aid injection / auto-commit)
	SSEDocs     = "docs"     // the document list gained or lost an entry
	SSEPing     = "ping"     // heartbeat, once every 25s, data is {}
)

// SSEComment is the data payload of an SSEComments event.
type SSEComment struct {
	Doc     string   `json:"doc"`
	Threads []string `json:"threads,omitempty"` // affected thread ids; empty means invalidate everything
	Rev     string   `json:"rev,omitempty"`
}

// SSEDocChange is the data payload of an SSEDoc event.
type SSEDocChange struct {
	Doc     string `json:"doc"`
	Kind    string `json:"kind"`             // content | remap | aid | remove
	Rev     string `json:"rev,omitempty"`    // new sha after auto-commit
	Remaps  int    `json:"remaps,omitempty"` // number of threads remapped this round
	Orphans int    `json:"orphans,omitempty"`
}
