// Package api defines art's **wire-level data contract** (DTOs).
//
// Frozen by convention: every type and JSON tag in this package is the one
// contract shared by the Go side, the CLI's --json output, and the frontend
// TypeScript types. No work package may change this package's field names,
// types, or tags; a change here has to go through the architecture layer and
// be kept in sync with docs/blueprint.md and web/src/lib/types.ts.
//
// This package depends on no other internal package and contains no logic,
// only types.
package api

import "time"

// ---------------------------------------------------------------------------
// Enum constants
// ---------------------------------------------------------------------------

// Document types.
const (
	DocTypeMD   = "md"
	DocTypeHTML = "html"
)

// Thread status. The current state after folding.
const (
	StatusOpen      = "open"
	StatusAddressed = "addressed"
	StatusResolved  = "resolved"
)

// Anchor kinds.
const (
	AnchorText    = "text"    // md body text anchor (TextQuote + TextPosition)
	AnchorElement = "element" // html element anchor (data-aid, optional quote)
)

// OrphanHint is the fixed hint shown to an agent for an orphaned thread
// (design doc §7; the wording itself must not be changed).
const OrphanHint = "The anchored text no longer exists — the feedback was likely addressed. Confirm with resolve, or re-anchor."

// ---------------------------------------------------------------------------
// Documents
// ---------------------------------------------------------------------------

// Doc is an artifact's summary information, used by the index page and
// `artx list`.
type Doc struct {
	ID         string    `json:"id"`       // 6-character base36 doc id, its identity
	Slug       string    `json:"slug"`     // directory name within the vault
	Title      string    `json:"title"`    // md frontmatter title or first h1; html takes <title>
	Type       string    `json:"type"`     // DocTypeMD | DocTypeHTML
	Path       string    `json:"path"`     // absolute path (to index.md / index.html)
	RelPath    string    `json:"rel_path"` // path relative to the vault root
	URL        string    `json:"url"`      // http://host:port/a/{id}
	Rev        string    `json:"rev"`      // short sha of the most recent commit touching this file; "" if untracked
	ModTime    time.Time `json:"mod_time"`
	Size       int64     `json:"size"`
	OpenCount  int       `json:"open_count"`  // number of open threads
	TotalCount int       `json:"total_count"` // total threads (including resolved, excluding archived)
}

// DocDetail carries everything a document page needs.
//
// Rendering red line: the HTML for md is generated by Go-side goldmark and
// carried in the HTML field; the frontend only does dangerouslySetInnerHTML
// plus overlays — it must **never** re-render markdown itself.
type DocDetail struct {
	Doc

	// md-only fields.
	HTML        string         `json:"html,omitempty"`        // rendered HTML; block elements carry data-sourcepos="start:end"
	BodyOffset  int            `json:"body_offset,omitempty"` // byte offset where the body starts (after frontmatter); all sourcepos values are file-absolute
	Frontmatter map[string]any `json:"frontmatter,omitempty"` // parsed frontmatter
	HasMermaid  bool           `json:"has_mermaid,omitempty"` // contains a ```mermaid code block; frontend lazy-loads mermaid on demand
	HasMath     bool           `json:"has_math,omitempty"`    // contains $ / $$; frontend lazy-loads katex on demand

	// html-only fields.
	RawURL string `json:"raw_url,omitempty"` // iframe src, of the form /raw/{id}/

	// Historical version viewing (?v=sha). Empty means the current working copy.
	Rev0 string `json:"rev0,omitempty"`
}

// DocsResponse is the response body for GET /api/docs.
type DocsResponse struct {
	Vault string `json:"vault"` // vault name (registry key); the directory name if unregistered
	Root  string `json:"root"`  // absolute vault path
	Docs  []Doc  `json:"docs"`
}

// ---------------------------------------------------------------------------
// Version diff
// ---------------------------------------------------------------------------

// Diff operations for md blocks and html elements.
const (
	DiffUnchanged = "unchanged" // md block present in both versions with identical content
	DiffModified  = "modified"  // md block kept its place but its content was edited
	DiffAdded     = "added"     // only in the new version
	DiffRemoved   = "removed"   // only in the old version
	DiffChanged   = "changed"   // html element kept its data-aid but its own content changed
)

// Diff hunk line operations.
const (
	DiffLineCtx = "ctx"
	DiffLineDel = "del"
	DiffLineAdd = "add"
)

// DiffBlock is the fate of one md top-level block between two versions.
// From/To are [start,end) **file-absolute byte ranges** in the old/new
// source; To doubles as the join key against the new version's rendered
// data-sourcepos. Blocks are listed in new-document order, with each removed
// block already inserted before its original successor — the frontend never
// has to re-sort.
type DiffBlock struct {
	Op           string   `json:"op"`                      // DiffUnchanged | DiffModified | DiffAdded | DiffRemoved
	From         []int    `json:"from,omitempty"`          // range in the old source; modified/removed only
	To           []int    `json:"to,omitempty"`            // range in the new source; absent for removed
	AddedTexts   []string `json:"added_texts,omitempty"`   // modified only: inserted source-text segments
	RemovedTexts []string `json:"removed_texts,omitempty"` // modified only: deleted source-text segments
	HTML         string   `json:"html,omitempty"`          // removed only: the block rendered against the old version
}

// DiffElement is the fate of one html element (identified by its stable
// data-aid) between two versions. Unchanged elements are not listed.
type DiffElement struct {
	Op   string `json:"op"`             // DiffChanged | DiffAdded | DiffRemoved
	AID  string `json:"aid"`            // the element's data-aid
	HTML string `json:"html,omitempty"` // removed only: the element's old outerHTML, for the "deleted elements" sidebar
}

// DiffLine is one line of a unified hunk.
type DiffLine struct {
	Op   string `json:"op"` // DiffLineCtx | DiffLineDel | DiffLineAdd
	Text string `json:"text"`
}

// DiffHunk is a unified-diff hunk over the raw source (3 context lines),
// shared by md and html documents for the source view.
type DiffHunk struct {
	FromStart int        `json:"from_start"` // 1-based first line in the old source
	FromCount int        `json:"from_count"`
	ToStart   int        `json:"to_start"` // 1-based first line in the new source
	ToCount   int        `json:"to_count"`
	Lines     []DiffLine `json:"lines"`
}

// DiffStats aggregates a diff for the toolbar. For html documents, Modified
// counts DiffChanged elements.
type DiffStats struct {
	Added    int `json:"added"`
	Removed  int `json:"removed"`
	Modified int `json:"modified"`
}

// DiffResponse is the response body for
// GET /api/docs/{id}/diff?from=<sha>[&to=<sha>].
type DiffResponse struct {
	Doc  string `json:"doc"`
	Type string `json:"type"` // DocTypeMD | DocTypeHTML
	From string `json:"from"` // old revision, echoed exactly as the caller passed it (any git rev)
	To   string `json:"to"`   // new revision, echoed as passed; "" means the working copy

	Blocks   []DiffBlock   `json:"blocks,omitempty"`   // md only
	Elements []DiffElement `json:"elements,omitempty"` // html only

	Hunks []DiffHunk `json:"hunks"` // unified source view, both types
	Stats DiffStats  `json:"stats"`

	FrontmatterChanged bool `json:"frontmatter_changed,omitempty"` // md only; Blocks covers the body alone
	ChromeChanged      bool `json:"chrome_changed,omitempty"`      // html only: head/style/script changed, element ops don't cover it
}

// ---------------------------------------------------------------------------
// Comment threads
// ---------------------------------------------------------------------------

// ThreadAnchor is a thread anchor's **presentation form**: the create
// event's anchor with the latest remap/orphan event applied on top, with the
// Line and Context fields filled in by the anchor package.
type ThreadAnchor struct {
	Kind      string `json:"kind"`                 // AnchorText | AnchorElement
	Exact     string `json:"exact,omitempty"`      // anchored text (source file excerpt)
	Prefix    string `json:"prefix,omitempty"`     // ~32 characters before Exact
	Suffix    string `json:"suffix,omitempty"`     // ~32 characters after Exact
	Start     int    `json:"start"`                // current byte offset (file-absolute), inclusive
	End       int    `json:"end"`                  // current byte offset, exclusive
	Line      int    `json:"line"`                 // 1-based line number of Start; derived field
	Context   string `json:"context,omitempty"`    // surrounding 2 lines of original text on each side; derived field
	AID       string `json:"aid,omitempty"`        // element anchor: the target element's data-aid
	Rev       string `json:"rev,omitempty"`        // git rev this offset corresponds to
	Approx    bool   `json:"approx,omitempty"`     // true = fell back to block-level anchoring, not an exact quote hit
	Orphan    bool   `json:"orphan,omitempty"`     // true = the anchored text no longer exists
	LastExact string `json:"last_exact,omitempty"` // preserves "what this used to point at" when orphaned
}

// Reply is a single reply within a thread.
type Reply struct {
	ID        string     `json:"id"`     // <thread>.<3-character base36>
	Author    string     `json:"author"` // e.g. cappu | agent:claude | artx-web <reviewer>
	Body      string     `json:"body"`
	CreatedAt time.Time  `json:"created_at"`
	EditedAt  *time.Time `json:"edited_at,omitempty"`
}

// Addressed records an agent's "handled this" declaration.
type Addressed struct {
	By     string    `json:"by"`
	Commit string    `json:"commit,omitempty"`
	Note   string    `json:"note,omitempty"`
	At     time.Time `json:"at"`
}

// Thread is a thread's current state after folding all of its events. It is
// the **same** output shape used by both `artx comments --json` and
// GET /api/docs/{id}/comments.
type Thread struct {
	Thread     string       `json:"thread"` // thread id, e.g. c7k2f9
	Doc        string       `json:"doc"`    // doc id
	Slug       string       `json:"slug"`   // convenient for an agent to locate the document
	Path       string       `json:"path"`   // absolute path to the document
	Status     string       `json:"status"` // StatusOpen | StatusAddressed | StatusResolved
	Author     string       `json:"author"` // who raised it
	Body       string       `json:"body"`   // root comment body (after collapsing the edit chain)
	CreatedAt  time.Time    `json:"created_at"`
	UpdatedAt  time.Time    `json:"updated_at"` // ts of this thread's most recent event
	EditedAt   *time.Time   `json:"edited_at,omitempty"`
	CreatedRev string       `json:"created_rev,omitempty"`
	Anchor     ThreadAnchor `json:"anchor"`
	Replies    []Reply      `json:"replies"`
	Addressed  *Addressed   `json:"addressed,omitempty"`
	Hint       string       `json:"hint,omitempty"` // set to OrphanHint when orphaned
}

// CommentsResponse is the response body for GET /api/docs/{id}/comments.
type CommentsResponse struct {
	Doc      string   `json:"doc"`
	Threads  []Thread `json:"threads"`
	Warnings []string `json:"warnings,omitempty"` // parse warnings: corrupt blocks, orphaned events, etc.
}

